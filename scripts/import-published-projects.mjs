import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const sourcePath = process.argv[2];

if (!sourcePath) {
  throw new Error("Usage: node scripts/import-published-projects.mjs <portfolio-projects.json>");
}

const projectRoot = resolve(import.meta.dirname, "..");
const publicRoot = join(projectRoot, "public", "projects", "published");
const modulePath = join(projectRoot, "app", "published-projects.ts");
const projects = JSON.parse(await readFile(resolve(sourcePath), "utf8"));

if (!Array.isArray(projects)) {
  throw new Error("The import file must contain a JSON array of projects.");
}

function slugify(value) {
  const slug = value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

  if (!slug) throw new Error(`Could not create a folder name for project: ${value}`);
  return slug;
}

function extensionForMime(mime) {
  const extensions = {
    "image/avif": ".avif",
    "image/gif": ".gif",
    "image/jpeg": ".jpg",
    "image/png": ".png",
    "image/svg+xml": ".svg",
    "image/webp": ".webp",
    "video/mp4": ".mp4",
    "video/quicktime": ".mov",
    "video/webm": ".webm",
  };
  return extensions[mime] ?? "";
}

async function materializeMedia(source, directory, basename) {
  if (typeof source !== "string" || !source.startsWith("data:")) return source;

  const match = source.match(/^data:([^;,]+);base64,(.+)$/s);
  if (!match) throw new Error(`Unsupported embedded media in ${directory}/${basename}`);

  const [, mime, payload] = match;
  const extension = extensionForMime(mime);
  if (!extension) throw new Error(`Unsupported media type: ${mime}`);

  const outputDirectory = join(publicRoot, directory);
  const outputPath = join(outputDirectory, `${basename}${extension}`);
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(outputPath, Buffer.from(payload, "base64"));
  return `/projects/published/${directory}/${basename}${extension}`;
}

const imported = [];

for (const sourceProject of projects) {
  if (!sourceProject?.title || !sourceProject?.id) {
    throw new Error("Every project needs an id and title.");
  }

  const directory = slugify(sourceProject.title);
  const image = await materializeMedia(sourceProject.image ?? "", directory, "cover");
  const gallery = [];

  for (const [index, item] of (sourceProject.gallery ?? []).entries()) {
    const source = typeof item === "string" ? item : item?.src;
    gallery.push(await materializeMedia(source, directory, `gallery-${String(index + 1).padStart(2, "0")}`));
  }

  const videos = [];
  for (const [index, item] of (sourceProject.videos ?? []).entries()) {
    const video = typeof item === "string" ? { src: item } : { ...item };
    if (!video.src) continue;
    video.src = await materializeMedia(video.src, directory, `video-${String(index + 1).padStart(2, "0")}`);
    videos.push(video);
  }

  imported.push({
    ...sourceProject,
    image,
    gallery,
    videos,
  });
}

const moduleSource = `// Generated by scripts/import-published-projects.mjs.\n// Re-run the importer after receiving a newer portfolio JSON file.\nimport type { Project } from "./project-types";\n\nexport const publishedProjects: Project[] = ${JSON.stringify(imported, null, 2)};\n`;

await writeFile(modulePath, moduleSource);

const mediaCount = imported.reduce(
  (count, project) => count + (project.image ? 1 : 0) + project.gallery.length + project.videos.filter((video) => video.src.startsWith("/projects/")).length,
  0,
);

console.log(`Imported ${imported.length} projects and wrote ${mediaCount} local media files.`);
